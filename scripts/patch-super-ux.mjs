function once(from, to, label) {
  const i = s.indexOf(from);
  if (i < 0) {
    console.error("MISS", label);
    process.exitCode = 1;
    return false;
  }
  if (s.indexOf(from, i + from.length) >= 0) {
    console.error("MULTI", label);
    process.exitCode = 1;
    return false;
  }
  s = s.slice(0, i) + to + s.slice(i + from.length);
  console.log("OK", label);
  return true;
}

